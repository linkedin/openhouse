"""Real Tables/HTS/MySQL containers; Python requests drive every view operation."""

import base64
import copy
import json
import subprocess
import time
import unittest
import uuid
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
from urllib.parse import unquote, urlparse

import requests


ROOT = Path(__file__).resolve().parents[2]
RECIPE = ROOT / 'infra/recipes/docker-compose/views-e2e/docker-compose.yml'
SCHEMA = json.dumps({
    'type': 'struct',
    'schema-id': 0,
    'fields': [{'id': 1, 'name': 'id', 'required': True, 'type': 'string'}],
})
INITIAL = 'INITIAL_VERSION'
SOURCE_DIALECT = 'openhouse.view.sourceDialect'


class ViewsDockerE2eTest(unittest.TestCase):
    @classmethod
    def compose(cls, *args):
        result = subprocess.run(
            ['docker', 'compose', '-p', cls.project, '-f', str(RECIPE), *args],
            cwd=ROOT, capture_output=True, text=True, timeout=240)
        if result.returncode:
            raise RuntimeError(
                f'Compose {args[0]} failed ({result.returncode}):\n'
                f'{result.stdout}\n{result.stderr}')
        return result.stdout.strip()

    @classmethod
    def setUpClass(cls):
        cls.project = 'views-e2e-' + uuid.uuid4().hex[:12]
        cls.addClassCleanup(cls.stop_stack)
        for service in ('tables', 'housetables'):
            jar = ROOT / f'build/{service}/libs/{service}.jar'
            if not jar.is_file():
                raise RuntimeError(f'Missing {jar}; build both services with bootJar first')
        token = (ROOT / 'services/common/src/main/resources/dummy.token').read_text().strip()
        cls.headers = {'Authorization': f'Bearer {token}'}
        claims = json.loads(base64.urlsafe_b64decode(token.split('.')[1] + '==='))
        cls.creator = json.loads(claims['sub'])['USER-ID']
        cls.compose('up', '-d')
        cls.tables = 'http://' + cls.compose('port', 'openhouse-tables', '8080')
        cls.hts = 'http://' + cls.compose('port', 'openhouse-housetables', '8080')
        cls.wait_ready(cls.hts + '/hts/tables/query')
        cls.wait_ready(cls.tables + '/v1/databases', cls.headers)

    @classmethod
    def stop_stack(cls):
        try:
            logs = cls.compose('logs', '--no-color')
            destination = ROOT / 'build/tables/reports/views-docker-e2e' / cls.project
            destination.mkdir(parents=True, exist_ok=True)
            (destination / 'services.log').write_text(logs)
        finally:
            cls.compose('down', '--volumes', '--remove-orphans')

    @classmethod
    def wait_ready(cls, url, headers=None):
        deadline = time.monotonic() + 120
        last = 'no response'
        while time.monotonic() < deadline:
            try:
                response = requests.get(url, headers=headers, timeout=3)
                if response.status_code == 200:
                    return
                last = f'{response.status_code}: {response.text[:300]}'
            except requests.ConnectionError as error:
                last = str(error)
            except requests.Timeout as error:
                last = str(error)
            time.sleep(1)
        raise AssertionError(f'Service did not become ready at {url}: {last}')

    @classmethod
    def sql(cls, statement):
        return cls.compose(
            'exec', '-T', 'mysql', 'sh', '-c',
            'MYSQL_PWD="$MYSQL_PASSWORD" exec mysql -u"$MYSQL_USER" '
            'oh_db --batch --skip-column-names --raw -e "$1"', 'mysql-query', statement)

    def setUp(self):
        self.database = 'docker_views_' + uuid.uuid4().hex[:16]
        self.databases = [self.database]
        self.addCleanup(self.cleanup_databases)
        self.seed_database(self.database)
        self.gate(self.database, True)

    def cleanup_databases(self):
        # All identifiers are generated by this fixture; a failed assertion never skips cleanup.
        for database in self.databases:
            self.sql(f"DELETE FROM user_table_row WHERE database_id='{database}';"
                     f"DELETE FROM table_toggle_rule WHERE database_pattern='{database}';")
            self.assertEqual('', self.sql(
                f"SELECT table_id FROM user_table_row WHERE database_id='{database}'"))

    def http(self, method, path, status, body=None, headers=None):
        response = requests.request(
            method, self.tables + path, json=body,
            headers=self.headers if headers is None else headers, timeout=30)
        self.assertEqual(status, response.status_code, response.text)
        return response.json() if response.content else None

    def collection(self, database=None):
        return f'/v1/databases/{database or self.database}/views'

    def item(self, view='view', database=None):
        return self.collection(database) + '/' + view

    def body(self, view='view', database=None):
        database = database or self.database
        return {
            'databaseId': database, 'viewId': view, 'schema': SCHEMA,
            'representations': [{'type': 'sql', 'dialect': 'spark',
                                 'sql': 'SELECT id FROM source_table'}],
            'defaultCatalog': 'openhouse', 'defaultNamespace': [database],
            'viewProperties': {'description': 'initial', SOURCE_DIALECT: 'spark'},
        }

    def seed_database(self, database):
        self.http('POST', f'/v1/databases/{database}/tables', 201, {
            'databaseId': database, 'tableId': 'seed', 'clusterId': 'LocalFSCluster',
            'tableType': 'PRIMARY_TABLE', 'baseTableVersion': INITIAL,
            'schema': SCHEMA, 'tableProperties': {},
        })

    def gate(self, database, enabled):
        self.sql(f"DELETE FROM table_toggle_rule WHERE feature='views' "
                 f"AND database_pattern='{database}';")
        if enabled:
            self.sql("INSERT INTO table_toggle_rule(feature,database_pattern,table_pattern) "
                     f"VALUES ('views','{database}','*')")

    def row(self, view='view', database=None):
        database = database or self.database
        result = self.sql(
            "SELECT JSON_OBJECT('type',entity_type,'pointer',metadata_location,"
            "'version',version,'storage',storage_type,'created',creation_time,"
            "'legacyVersion',table_version,'etl',CAST(ETL_TS AS CHAR)) "
            f"FROM user_table_row WHERE database_id='{database}' AND table_id='{view}'")
        return json.loads(result) if result else None

    def metadata(self, response):
        path = unquote(urlparse(response['metadataLocation']).path)
        self.assertTrue(path.startswith('/data/openhouse/'), path)
        return json.loads(self.compose('exec', '-T', 'openhouse-tables', 'cat', path))

    def file_count(self):
        return len(self.compose(
            'exec', '-T', 'openhouse-tables', 'find', '/data/openhouse',
            '-name', '*.metadata.json').splitlines())

    def persisted(self, response, view='view', database=None):
        database = database or self.database
        row = self.row(view, database)
        self.assertIsNotNone(row)
        self.assertEqual('VIEW', row['type'])
        self.assertEqual('local', row['storage'])
        self.assertIsNone(row['legacyVersion'])
        self.assertEqual(response['metadataLocation'], row['pointer'])
        self.assertEqual(row['pointer'], response['viewVersion'])
        self.assertEqual(response['creationTime'], row['created'])
        for kind in ('views', 'entities'):
            result = requests.get(
                self.hts + f'/hts/{kind}',
                params={'databaseId': database, 'tableId': view}, timeout=30)
            self.assertEqual(200, result.status_code, result.text)
            entity = result.json()['entity']
            self.assertEqual('VIEW', entity['entityType'])
            self.assertEqual(row['pointer'], entity['metadataLocation'])
            self.assertEqual(row['pointer'], entity['tableVersion'])
        metadata = self.metadata(response)
        self.assertIn(metadata['view-uuid'], row['pointer'])
        self.assertEqual(metadata['view-uuid'], metadata['properties']['openhouse.tableUUID'])
        version = next(version for version in metadata['versions']
                       if version['version-id'] == metadata['current-version-id'])
        self.assertEqual('spark', version['summary']['sourceDialect'])
        self.assertNotIn(SOURCE_DIALECT, metadata['properties'])
        return row

    def test_lifecycle_noop_stale_write_and_metadata_response(self):
        body = self.body()
        created = self.http('POST', self.collection(), 201, body)
        before = self.persisted(created)
        self.assertEqual(0, before['version'])
        self.assertEqual(self.creator, created['viewCreator'])
        fetched = self.http('GET', self.item(), 200)
        self.assertEqual(created, fetched)
        metadata = self.metadata(created)
        files = self.file_count()
        self.http('POST', self.collection(), 409, body)
        self.assertEqual(before, self.row())
        body['baseMetadataLocation'] = created['metadataLocation']
        unchanged = self.http('PUT', self.item(), 200, body)
        self.assertEqual(before, self.persisted(unchanged))
        self.assertEqual(files, self.file_count())
        body['viewProperties']['description'] = 'updated'
        updated = self.http('PUT', self.item(), 200, body)
        after = self.persisted(updated)
        self.assertEqual(1, after['version'])
        self.assertNotEqual(created['metadataLocation'], updated['metadataLocation'])
        self.assertEqual(metadata['view-uuid'], self.metadata(updated)['view-uuid'])
        self.assertEqual(self.creator, updated['viewCreator'])
        self.assertGreater(updated['lastModifiedTime'], created['lastModifiedTime'])
        self.assertEqual(updated, self.http('GET', self.item(), 200))
        files = self.file_count()
        self.http('PUT', self.item(), 409, body)
        self.assertEqual(after, self.row())
        self.assertEqual(files, self.file_count())
        self.http('DELETE', self.item(), 204)
        self.assertIsNone(self.row())
        self.http('GET', self.item(), 404)
        self.http('DELETE', self.item(), 404)
        missing = requests.get(
            self.hts + '/hts/entities',
            params={'databaseId': self.database, 'tableId': 'view'}, timeout=30)
        self.assertEqual(404, missing.status_code, missing.text)

    def test_database_gate_isolation_and_reenable(self):
        other = self.database + '_off'
        self.databases.append(other)
        self.seed_database(other)
        created = self.http('POST', self.collection(), 201, self.body())
        before = self.persisted(created)
        files = self.file_count()
        body = self.body(database=other)
        body['viewProperties']['views.enabled'] = 'true'
        self.http('POST', self.collection(other), 404, body)
        body['baseMetadataLocation'] = INITIAL
        self.http('PUT', self.item(database=other), 404, body)
        for method, path in (
                ('GET', self.collection(other)), ('GET', self.item(database=other)),
                ('DELETE', self.item(database=other))):
            self.http(method, path, 404)
        self.assertIsNone(self.row(database=other))
        self.assertEqual(files, self.file_count())
        self.assertEqual(created, self.http('GET', self.item(), 200))
        self.assertEqual(before, self.row())
        self.gate(other, True)
        enabled = self.http('POST', self.collection(other), 201, self.body(database=other))
        other_before = self.persisted(enabled, database=other)
        self.gate(other, False)
        self.http('DELETE', self.item(database=other), 404)
        self.assertEqual(other_before, self.row(database=other))
        self.gate(other, True)
        self.http('DELETE', self.item(database=other), 204)
        self.assertIsNone(self.row(database=other))
        self.assertEqual(before, self.row())

    def test_pagination_across_hts_pages(self):
        expected = [f'view_{index:03d}' for index in range(53)]
        for view in expected:
            self.http('POST', self.collection(), 201, self.body(view))
        page = self.http('GET', self.collection() + '?size=7', 200)
        self.assertEqual(7, len(page['results']))
        first_token = page['nextPageToken']
        actual, tokens = [], set()
        while True:
            actual.extend(item['viewId'] for item in page['results'])
            self.assertTrue(all(item['databaseId'] == self.database for item in page['results']))
            token = page.get('nextPageToken')
            if not token:
                break
            self.assertNotIn(token, tokens)
            tokens.add(token)
            self.assertLess(len(tokens), 10)
            response = requests.get(
                self.tables + self.collection(),
                params={'size': 11, 'pageToken': token}, headers=self.headers, timeout=30)
            self.assertEqual(200, response.status_code, response.text)
            page = response.json()
            self.assertLessEqual(len(page['results']), 11)
        self.assertEqual(expected, actual)
        self.assertEqual(53, len(set(actual)))
        self.assertEqual('53', self.sql(
            f"SELECT COUNT(*) FROM user_table_row WHERE database_id='{self.database}' "
            "AND entity_type='VIEW'"))
        files = self.file_count()
        self.http('GET', self.collection() + '?pageToken=broken', 400)
        self.http('GET', self.collection() + '?size=0', 400)
        self.assertEqual(files, self.file_count())
        other = self.database + '_other'
        self.databases.append(other)
        self.seed_database(other)
        self.gate(other, True)
        response = requests.get(
            self.tables + self.collection(other), params={'size': 11, 'pageToken': first_token},
            headers=self.headers, timeout=30)
        self.assertEqual(400, response.status_code, response.text)

    def test_table_view_collision_and_name_reuse(self):
        seed = self.row('seed')
        self.http('POST', self.collection(), 409, self.body('seed'))
        self.assertEqual(seed, self.row('seed'))
        created = self.http('POST', self.collection(), 201, self.body())
        before = self.persisted(created)
        table = {
            'databaseId': self.database, 'tableId': 'view', 'clusterId': 'LocalFSCluster',
            'tableType': 'PRIMARY_TABLE', 'baseTableVersion': INITIAL,
            'schema': SCHEMA, 'tableProperties': {},
        }
        table_collection = f'/v1/databases/{self.database}/tables'
        self.http('POST', table_collection, 409, table)
        self.http('GET', table_collection + '/view', 404)
        self.assertEqual(before, self.row())
        self.http('DELETE', self.item(), 204)
        self.http('POST', table_collection, 201, table)
        self.assertEqual('TABLE', self.row()['type'])
        self.http('GET', self.item(), 404)
        self.http('DELETE', table_collection + '/view?purge=true', 204)
        self.assertIsNone(self.row())

    def test_invalid_definition_and_missing_auth_leave_no_state(self):
        body = self.body()
        files = self.file_count()
        invalid = copy.deepcopy(body)
        invalid['representations'] = []
        self.http('POST', self.collection(), 400, invalid)
        self.http('POST', self.collection(), 401, body, headers={})
        self.assertIsNone(self.row())
        self.assertEqual(files, self.file_count())

    def test_source_dialect_property_validation_and_immutability(self):
        files = self.file_count()
        for invalid in ('missing', 'null', 'blank', 'unsupported', 'unrepresented', 'legacy'):
            with self.subTest(invalid=invalid):
                body = self.body()
                if invalid in ('missing', 'legacy'):
                    del body['viewProperties'][SOURCE_DIALECT]
                    if invalid == 'legacy':
                        body['sourceDialect'] = 'spark'
                else:
                    body['viewProperties'][SOURCE_DIALECT] = {
                        'null': None, 'blank': ' ', 'unsupported': 'other',
                        'unrepresented': 'trino',
                    }[invalid]
                self.http('POST', self.collection(), 400, body)
                self.assertIsNone(self.row())
                self.assertEqual(files, self.file_count())

        created = self.http('POST', self.collection(), 201, self.body())
        before = self.persisted(created)
        files = self.file_count()
        body = self.body()
        body['baseMetadataLocation'] = created['metadataLocation']
        body['viewProperties'][SOURCE_DIALECT] = 'trino'
        body['representations'].append({
            'type': 'sql', 'dialect': 'trino', 'sql': 'SELECT id FROM source_table',
        })
        self.http('PUT', self.item(), 400, body)
        self.assertEqual(before, self.persisted(self.http('GET', self.item(), 200)))
        self.assertEqual(files, self.file_count())

    def test_concurrent_replaces_publish_one_winner(self):
        created = self.http('POST', self.collection(), 201, self.body())
        before = self.persisted(created)

        def replace(writer):
            body = self.body()
            body['baseMetadataLocation'] = created['metadataLocation']
            body['viewProperties']['writer'] = str(writer)
            return requests.put(
                self.tables + self.item(), json=body, headers=self.headers, timeout=30)

        with ThreadPoolExecutor(max_workers=2) as executor:
            responses = list(executor.map(replace, (1, 2)))
        self.assertEqual([200, 409], sorted(response.status_code for response in responses),
                         [response.text for response in responses])
        winner = next(response.json() for response in responses if response.status_code == 200)
        after = self.persisted(winner)
        self.assertEqual(before['version'] + 1, after['version'])
        self.assertEqual(winner, self.http('GET', self.item(), 200))


